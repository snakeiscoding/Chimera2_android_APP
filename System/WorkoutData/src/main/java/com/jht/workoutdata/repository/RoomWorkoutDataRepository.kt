package com.jht.workoutdata.repository

import android.content.Context
import android.database.Cursor
import com.jht.workoutdata.db.WorkoutDataPointEntity
import com.jht.workoutdata.db.WorkoutDatabase
import com.jht.workoutdata.model.MetricSample
import com.jht.workoutdata.model.WorkoutDataPoint
import com.jht.workoutdata.model.WorkoutFutureData
import com.jht.workoutdata.model.WorkoutMetric
import com.jht.workoutdata.query.WorkoutDataQuery

/**
 * Room-backed [WorkoutDataRepository] over an in-memory database.
 *
 * One row per workout second is a storage invariant: `elapsed_time_sec` is
 * unique, and adding a point for an existing second overrides it (last write
 * wins). Window and down-sample logic runs in SQL (see the DAO) on the
 * `elapsed_time_sec` axis. The "last N" window is computed relative to the
 * *latest* stored point's elapsed time, so it is deterministic regardless of
 * when the read happens.
 *
 * A bounded retention guard ([maxRows]) trims the oldest rows after each insert
 * so an unexpectedly long session can't grow memory without limit. Normal usage
 * calls [clear] at the start of each workout, so a single session rarely
 * approaches the cap.
 *
 * @param db Injectable for tests; defaults to a fresh in-memory database.
 */
class RoomWorkoutDataRepository(
    context: Context,
    private val maxRows: Int = DEFAULT_MAX_ROWS,
    db: WorkoutDatabase = WorkoutDatabase.inMemory(context),
) : WorkoutDataRepository {

    init {
        require(maxRows > 0) { "maxRows must be > 0, was $maxRows" }
    }

    private val dao = db.workoutDataDao()

    // Planned (future) profiles. Replaced wholesale, so a volatile immutable value is
    // sufficient for cross-thread safety; not persisted in Room since it is transient
    // script/terrain data that is regenerated by the workout engine.
    @Volatile
    private var future = WorkoutFutureData()

    override fun addPoint(point: WorkoutDataPoint) {
        dao.insert(WorkoutDataPointEntity.fromDomain(point))
        dao.trimToMostRecent(maxRows)
    }

    override fun queryPoints(query: WorkoutDataQuery): List<WorkoutDataPoint> {
        if (query.hasRange) {
            return dao.pointsBetween(query.fromSec ?: Int.MIN_VALUE, query.toSec ?: Int.MAX_VALUE)
                .map { it.toDomain() }
        }
        val since = sinceFor(query)
        val rows = if (query.hasDownsample) {
            dao.pointsSinceDownsampled(since, query.downsampleSec!!)
        } else {
            dao.pointsSince(since)
        }
        return rows.map { it.toDomain() }
    }

    override fun querySeries(metric: WorkoutMetric, query: WorkoutDataQuery): List<MetricSample> =
        queryPoints(query).map { point ->
            MetricSample(
                elapsedTimeSec = point.elapsedTimeSec,
                value = point.valueOf(metric),
            )
        }

    override fun queryCursor(query: WorkoutDataQuery): Cursor {
        if (query.hasRange) {
            return dao.pointsBetweenCursor(query.fromSec ?: Int.MIN_VALUE, query.toSec ?: Int.MAX_VALUE)
        }
        val since = sinceFor(query)
        return if (query.hasDownsample) {
            dao.pointsSinceDownsampledCursor(since, query.downsampleSec!!)
        } else {
            dao.pointsSinceCursor(since)
        }
    }

    override fun setFuture(future: WorkoutFutureData) {
        this.future = future
    }

    override fun getFuture(): WorkoutFutureData = future

    override fun clear() {
        dao.clear()
        future = WorkoutFutureData() // the future belongs to the workout being cleared
    }

    override fun count(): Int = dao.count()

    /**
     * Lower-bound elapsed second for the query. With no window, returns
     * [Int.MIN_VALUE] (everything). With a window but an empty table, returns
     * [Int.MAX_VALUE] so nothing matches.
     */
    private fun sinceFor(query: WorkoutDataQuery): Int {
        if (!query.hasWindow) return Int.MIN_VALUE
        val latest = dao.latestElapsedSec() ?: return Int.MAX_VALUE
        return latest - query.windowSec!!
    }

    companion object {
        /** ~8 hours at 1 Hz; a safety ceiling, not the normal working size. */
        const val DEFAULT_MAX_ROWS = 8 * 60 * 60
    }
}
