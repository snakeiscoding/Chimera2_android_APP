 * Fixed console index for web zones whose console IANA id is used by more than one entry.
 *
 * Index 28 and 30 are both Europe/Belgrade (same clock time) but name different cities, so a
 * lookup by id alone would always give 28. [WebTimeZoneMapper] uses the index here only while that
 * entry still has the id from [WEB_TO_CONSOLE_TIMEZONES]; otherwise it takes the first match.
 */
internal val WEB_TO_CONSOLE_INDEX: Map<String, Int> = mapOf(
    // 30: "Sarajevo, Skopje, Warsaw, Zagreb". The rest of Europe/Belgrade stays on 28.
    "Europe/Sarajevo" to 30,
    "Europe/Skopje"   to 30,
    "Europe/Warsaw"   to 30,
    "Europe/Zagreb"   to 30,
)

